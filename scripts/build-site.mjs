#!/usr/bin/env node
// Builds generated parts of apps/web from the single design source and real results:
//   apps/web/assets/theme.css    <- packages/runner/src/design/theme.ts (THEME_CSS)
//   apps/web/sample-report.html  <- examples/results/*.json via the real report renderer
//   apps/web/favicon.svg         <- LOGO_SVG
// Run after `pnpm build`.  Images (report preview, OG card) are rendered separately by
// scripts/render-site-images.mjs because they need a browser.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = fileURLToPath(new URL('..', import.meta.url));
const web = join(repo, 'apps', 'web');
const { THEME_CSS, LOGO_SVG } = await import(join(repo, 'packages/runner/dist/design/theme.js'));
const { renderHtmlReport } = await import(join(repo, 'packages/runner/dist/html-report.js'));
const { validateSchema } = await import(join(repo, 'packages/contracts/dist/index.js'));

mkdirSync(join(web, 'assets'), { recursive: true });
writeFileSync(join(web, 'assets', 'theme.css'), `/* GENERATED from packages/runner/src/design/theme.ts by scripts/build-site.mjs. Do not edit. */\n${THEME_CSS.trim()}\n`);

const dir = join(repo, 'examples', 'results');
const results = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => {
    const v = validateSchema('RunResult', JSON.parse(readFileSync(join(dir, f), 'utf8')));
    if (!v.ok) throw new Error(`${f} is not a valid RunResult`);
    return v.value;
  });
const report = renderHtmlReport(results, { client: 'Invoice Portal (demo)', preparedBy: 'Pyx' }).replace(
  '<body class="rp rp-report">',
  '<body class="rp rp-report">\n<div class="rp-noprint" style="text-align:center;padding:10px 16px;font-size:13px;color:#a3b1c4;border-bottom:1px solid rgba(148,170,200,.14)">Sample report generated from real runs: release 41 is healthy; in release 42 the demo app’s API route fetches invoices with the secret key · <a href="index.html">Back to Pyx</a></div>',
);
writeFileSync(join(web, 'sample-report.html'), report);

// In-browser verifier: the CLI's compare/outcome code bundled for apps/web/verify.html.
const { build } = await import(join(repo, 'packages/cli/node_modules/esbuild/lib/main.js'));
await build({
  entryPoints: [join(repo, 'scripts/web/verify-entry.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  outfile: join(web, 'assets', 'verify-lib.js'),
  banner: { js: '/* GENERATED by scripts/build-site.mjs from packages/runner/src/compare.ts and packages/contracts/src/outcome.ts. Do not edit. */' },
});
// The sample results the verifier can load (real runs; see examples/results).
mkdirSync(join(web, 'samples'), { recursive: true });
for (const f of readdirSync(dir).filter((x) => x.endsWith('.json'))) writeFileSync(join(web, 'samples', f), readFileSync(join(dir, f)));

// The trust page shows a real request ledger (examples/ledgers/, copied from an integration run).
const ledgerDir = join(repo, 'examples', 'ledgers');
const ledgerFile = readdirSync(ledgerDir).filter((f) => f.endsWith('.requests.json')).sort()[0];
if (ledgerFile) {
  const { requests } = JSON.parse(readFileSync(join(ledgerDir, ledgerFile), 'utf8'));
  const e = (t) => String(t).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  const PURPOSE = { 'fixture-check': 'verify test records', identity: 'verify user', 'anonymous-context': 'verify anonymous', read: 'read', 'fixture-recheck': 're-check test records' };
  const rows = requests
    .map((q) => `          <tr><td class="mono">${q.n}</td><td>${e(PURPOSE[q.purpose] ?? q.purpose)}</td><td class="mono">${e(q.as)}</td><td class="mono url">GET ${e(decodeURIComponent(q.url.replace(/^https?:\/\/[^/]+/, '')))}</td><td class="mono">${e(q.failure ?? q.status)}</td></tr>`)
    .join('\n');
  const table = `<!-- ledger:start -->\n        <div class="table-wrap"><table class="table"><thead><tr><th>#</th><th>Why</th><th>As</th><th>Request</th><th>Status</th></tr></thead><tbody>\n${rows}\n        </tbody></table></div>\n        <!-- ledger:end -->`;
  const trustPath = join(web, 'trust.html');
  const trust = readFileSync(trustPath, 'utf8');
  writeFileSync(trustPath, trust.replace(/<!-- ledger:start -->[\s\S]*<!-- ledger:end -->/, () => table));
}

const favicon = LOGO_SVG.replace('class="rp-logo" ', 'xmlns="http://www.w3.org/2000/svg" width="32" height="32" ').replace(' aria-hidden="true" focusable="false"', '');
writeFileSync(join(web, 'favicon.svg'), favicon + '\n');
console.log(`site built: theme.css, sample-report.html (${results.length} runs), favicon.svg`);
